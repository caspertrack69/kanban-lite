import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(root, "designsystem.json");

let design;
try {
  design = JSON.parse(await readFile(sourcePath, "utf8"));
} catch (error) {
  console.error(
    `Cannot generate design tokens: ${sourcePath} is missing or unreadable.`,
  );
  console.error(
    "The committed generated files are still enough to build and run the app.",
  );
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
}

