const status = semantic.status;
const font = typography.fontFamily;
const scale = typography.scale;

const hexToRgba = (hex, alpha) => {
  const normalized = hex.replace("#", "");
  const value =
    normalized.length === 3
      ? normalized
          .split("")
          .map((part) => part + part)
          .join("")
      : normalized;
  const int = Number.parseInt(value, 16);
  const r = (int >> 16) & 255;
  const g = (int >> 8) & 255;
  const b = int & 255;
  return `rgba(${r},${g},${b},${alpha})`;
};

const fontStack = font.fallbackStack
  .split(",")
  .map((part) => part.trim().replace(/^['"]|['"]$/g, ""))
  .map((part) => {
    if (part === "Inter") return "var(--font-inter, 'Inter')";
    if (["Arial", "system-ui", "sans-serif"].includes(part)) return part;
    return `'${part}'`;
  })
  .join(", ");

